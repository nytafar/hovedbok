-- Seed: the SAF-T standard chart of accounts (std_account) and the SAF-T
-- grouping that maps every standard account to GroupingCategory/GroupingCode.
-- bootstrap_entity() (0012) copies this chart into an entity's own accounts.
--
-- Provenance
--   std_account rows: enkelt-regnskap seed/standardkontoplan.csv (commit 6b937b6,
--   2026-10-01, sha256 f2938c09…), itself an unchanged copy of Skatteetaten/saf-t
--   "General Ledger Standard Accounts/CSV/General_Ledger_Standard_Accounts_4_character.csv"
--   at commit c25524c (2023-02-01): 4-digit standard accounts built on NS 4102,
--   Norwegian and English descriptions. Copyright Regnskap Norge AS 2018; the list
--   may only be used in connection with SAF-T mapping.
--   grouping_range rows: enkelt-regnskap seed/gruppering.csv (same commit,
--   sha256 4f654bfa…): hand-made ranges fra;til;gruppe_kategori;gruppe_kode onto
--   the "Grouping Category Code 2025-2026" list (næringsspesifikasjon), an
--   approximation tuned for a sole proprietorship.
--   Both value lists below are the CSV rows verbatim, in file order. Do not edit
--   them here: a changed chart is a new migration.
--
-- The rules at the bottom (control accounts, 27xx VAT defaults and sides) are
-- hand-written policy, not part of the upstream lists.

-- One row per SAF-T standard account. grouping_* is filled from grouping_range;
-- default_vat/control/vat_side are the standard chart's own policy, copied to
-- entity accounts on bootstrap (vat_side drives vat_summary in 0012).
create table std_account (
  code              text primary key check (code ~ '^\d{4}$'),
  name              text not null,
  name_en           text not null,
  grouping_category text,
  grouping_code     text,
  default_vat       text references vat_code,
  -- control accounts tie postings to the customer/supplier subledgers (0003)
  control           text check (control in ('customer', 'supplier')),
  -- VAT accounts: which side of the MVA return the posted amount belongs to
  vat_side          text check (vat_side in ('output', 'input'))
);

-- Inclusive account-number ranges onto a SAF-T grouping category and code.
-- Also the lookup for an entity's own non-standard accounts.
create table grouping_range (
  from_code text primary key check (from_code ~ '^\d{4}$'),
  to_code   text not null check (to_code ~ '^\d{4}$'),
  category  text not null,
  code      text not null,
  check (from_code <= to_code)
);

