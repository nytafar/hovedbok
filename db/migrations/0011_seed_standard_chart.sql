-- Ranges must not overlap, and a grouping code belongs to one category only, so
-- account.grouping (the code) determines GroupingCategory unambiguously.
do $$
declare
  bad text;
begin
  select a.from_code into bad from grouping_range a join grouping_range b
      on a.from_code < b.from_code and b.from_code <= a.to_code
   limit 1;
  if found then
    raise exception 'grouping_range % overlaps the next range', bad;
  end if;
  select code into bad from grouping_range group by code
  having count(distinct category) > 1 limit 1;
  if found then
    raise exception 'grouping code % appears under more than one category', bad;
  end if;
end
$$;

update std_account s
   set grouping_category = g.category, grouping_code = g.code
  from grouping_range g
 where s.code between g.from_code and g.to_code;

